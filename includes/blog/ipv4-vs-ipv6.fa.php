<p>اگر تا امروز آدرس IP دیده باشید، به احتمال زیاد چیزی شبیه <code>203.0.113.42</code> بوده — این یک آدرس <strong>IPv4</strong> است. اما به‌مرور، اینترنت در حال گذار به نسل جدیدی به نام <strong>IPv6</strong> است. در این مقاله تفاوت این دو و دلیل این تغییر را ساده توضیح می‌دهیم.</p>

<h2>IPv4 چیست؟</h2>
<p>IPv4 از چهار بلوک عددی بین ۰ تا ۲۵۵ تشکیل شده که با نقطه از هم جدا می‌شوند (مثل <code>192.168.1.10</code>). این ساختار در مجموع حدود <strong>۴.۳ میلیارد</strong> آدرس یکتا فراهم می‌کند — عددی که در دهه ۱۹۸۰ بسیار بزرگ به نظر می‌رسید، اما با رشد انفجاری موبایل، دستگاه‌های هوشمند و IoT، عملاً تمام شده است.</p>

<h2>IPv6 چیست؟</h2>
<p>IPv6 برای حل همین مشکل کمبود آدرس طراحی شد. این نسخه از هشت گروه چهار-رقمی هگزادسیمال استفاده می‌کند، مثل:</p>
<blockquote>2001:0db8:85a3:0000:0000:8a2e:0370:7334</blockquote>
<p>این ساختار فضایی در حدود <strong>۳۴۰ تریلیون تریلیون تریلیون</strong> آدرس فراهم می‌کند — عملاً برای هر دانه شن روی کره زمین می‌توان چند آدرس یکتای IPv6 اختصاص داد.</p>

