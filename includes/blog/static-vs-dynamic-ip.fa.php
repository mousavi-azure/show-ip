<h2>آی‌پی پویا (Dynamic IP) چیست؟</h2>
<p>در آی‌پی پویا، ISP یک آدرس IP را از یک استخر (Pool) مشترک به‌طور موقت به اتصال شما اختصاص می‌دهد. این آدرس ممکن است بعد از خاموش‌روشن‌کردن مودم، اتمام مدت اجاره (Lease Time) یا حتی بدون هیچ دلیل مشخصی تغییر کند. تقریباً تمام اتصال‌های خانگی و موبایل به‌صورت پیش‌فرض پویا هستند، چون این روش برای ISP از نظر مدیریت منابع محدود آی‌پی، بسیار کارآمدتر است.</p>

<h2>آی‌پی ثابت (Static IP) چیست؟</h2>
<p>در آی‌پی ثابت، یک آدرس IP مشخص به‌طور دائم به یک اتصال یا سرور اختصاص داده می‌شود و تغییر نمی‌کند — مگر اینکه به‌صورت دستی تغییر کند. این نوع آی‌پی معمولاً باید جداگانه از ISP یا شرکت میزبانی خریداری شود و برای مواردی که نیاز به آدرس قابل‌اعتماد و همیشگی دارند، ضروری است.</p>

