<p>وقتی در گوگل می‌نویسید «آی‌پی من چیست» یا «نمایش آی‌پی من»، در واقع دنبال یک عدد هستید: همان آدرسی که سرورهای اینترنت با آن شما را می‌شناسند. صفحه اصلی <a href="/">Show-IP.ir</a> این عدد را بلافاصله نشان می‌دهد، اما نتیجه چند خط دیگر هم دارد که فهمیدنشان کمک می‌کند بدانید اینترنت شما واقعاً چه وضعیتی دارد.</p>

<h2>آدرس IP عمومی شما کدام است؟</h2>
<p>عددی که بالای صفحه با فرمت چهاربخشی مثل <code>5.115.xxx.xxx</code> می‌بینید، <strong>آی‌پی عمومی (Public IP)</strong> شماست. این همان آدرسی است که هر سایت، بازی آنلاین یا سرویسی که استفاده می‌کنید می‌بیند. اگر IPv6 هم داشته باشید، ممکن است یک آدرس طولانی‌تر با حروف و دونقطه هم ببینید؛ تفاوت این دو را در <a href="/blog/ipv4-vs-ipv6">تفاوت IPv4 و IPv6</a> توضیح داده‌ایم.</p>
<p>این آدرس با آی‌پی‌ای که در تنظیمات ویندوز یا روتر می‌بینید (مثل <code>192.168.1.5</code>) فرق دارد؛ آن یکی <a href="/blog/private-vs-public-ip">آی‌پی خصوصی</a> است و فقط داخل شبکه خانه شما معنا دارد.</p>

<h2>معنی هر خط از نتیجه</h2>
<ul>
<li><strong>کشور و شهر:</strong> از روی بلوک آدرس IP و پایگاه‌داده‌های جغرافیایی تخمین زده می‌شود — نه با GPS. برای همین گاهی شهر اشتباه است.</li>
<li><strong>ISP / اپراتور:</strong> نام شرکتی که این آدرس به آن اختصاص داده شده؛ مثلاً «Mobile Communication Company of Iran» برای همراه اول یا «Pishgaman» و «Shatel» برای اینترنت ثابت.</li>
<li><strong>ASN و Route:</strong> شماره شبکه‌ای که آی‌پی شما در آن قرار دارد. برای کاربر عادی مهم نیست، اما برای تشخیص مشکلات مسیر (routing) به کار می‌آید.</li>
<li><strong>منطقه زمانی و ارز:</strong> از روی کشورِ تخمینی پر می‌شود.</li>
<li><strong>وضعیت امنیتی:</strong> بررسی می‌کند آی‌پی شما به‌عنوان Tor، پروکسی، دیتاسنتر یا VPN شناخته می‌شود یا نه.</li>
</ul>

<h2>چرا موقعیت مکانی‌ام اشتباه است؟</h2>
<p>سه دلیل رایج در ایران:</p>
<ul>
<li><strong>NAT اپراتور (CGNAT):</strong> بیشتر اپراتورهای موبایل و بعضی ISPها یک آدرس عمومی را بین صدها مشترک به اشتراک می‌گذارند. آدرسی که می‌بینید ممکن است به مرکز دیتای اپراتور در شهر دیگری ثبت شده باشد.</li>
<li><strong>VPN یا فیلترشکن روشن:</strong> در این حالت کشور و شهرِ نمایش‌داده‌شده مربوط به سرور VPN است، نه شما. جزئیات در <a href="/blog/how-vpn-changes-your-ip">VPN چگونه آی‌پی را تغییر می‌دهد</a>.</li>
<li><strong>به‌روز نبودن پایگاه‌داده:</strong> وقتی اپراتور بلوک جدیدی می‌گیرد، چند هفته طول می‌کشد تا در دیتابیس‌های جهانی ثبت شود.</li>
</ul>
<p>اگر موقعیت دقیق می‌خواهید، از دکمه «استفاده از موقعیت دقیق من» در صفحه اصلی استفاده کنید؛ این گزینه از GPS مرورگر استفاده می‌کند و هیچ داده‌ای به سرور ارسال نمی‌شود.</p>

