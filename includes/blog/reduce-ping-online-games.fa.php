<p>پینگ (Ping) یا همان <em>latency</em>، مدت‌زمانی است که یک بسته داده از دستگاه شما به سرور بازی می‌رسد و پاسخش برمی‌گردد؛ برحسب میلی‌ثانیه (ms). پینگ پایین یعنی واکنش سریع‌تر بازی. برخلاف تصور رایج، سرعت دانلود بالا لزوماً به معنی پینگ پایین نیست — چیزی که مهم است، <strong>مسیر و کیفیت اتصال تا سرور</strong> است.</p>

